const assert = require('node:assert/strict')
const steam = require(process.argv[2])
const restart = process.argv[3] === '1'

async function run() {
    assert.equal(steam.restartAppIfNecessary(3104020), restart)
    console.log(`restartAppIfNecessary: ${restart}`)
    const client = steam.init(3104020)
    assert.equal(client.utils.getAppId(), 3104020)
    assert.equal(client.localplayer.getName(), 'Fixture Steam player')
    const id = client.localplayer.getSteamId().steamId64
    assert.equal(id, 76561198012345678n)
    assert.equal(client.apps.isAppInstalled(3104020), true)
    assert.equal(client.apps.isAppInstalled(480), false)
    console.log(`appId: 3104020, name: Fixture Steam player, steamId64: ${id}, ownership: true/false`)
    assert.equal(client.stats.setInt('GAMES_WON', 42), true)
    assert.equal(client.stats.getInt('GAMES_WON'), 42)
    assert.equal(client.stats.store(), true)
    assert.equal(client.achievement.isActivated('FIXTURE_ACHIEVEMENT'), false)
    assert.equal(client.achievement.activate('FIXTURE_ACHIEVEMENT'), true)
    assert.equal(client.achievement.isActivated('FIXTURE_ACHIEVEMENT'), true)
    assert.equal(client.achievement.clear('FIXTURE_ACHIEVEMENT'), true)
    assert.equal(client.achievement.isActivated('FIXTURE_ACHIEVEMENT'), false)
    assert.equal(client.achievement.activate('FIXTURE_ACHIEVEMENT'), true)
    assert.equal(client.stats.resetAll(true), true)
    assert.equal(client.stats.getInt('GAMES_WON'), 0)
    assert.equal(client.achievement.isActivated('FIXTURE_ACHIEVEMENT'), false)
    console.log('stats: set/get/store/reset, achievements: activate/check/clear/reset')
    const first = await client.auth.getSessionTicketWithSteamId(id, 5)
    assert.deepEqual(first.getBytes(), Buffer.from([0xf1, 0, 1]))
    first.cancel()
    const second = await client.auth.getSessionTicketWithSteamId(id, 5)
    assert.deepEqual(second.getBytes(), Buffer.from([0xf1, 0, 2]))
    second.cancel()
    const web = await client.auth.getAuthTicketForWebApi('deviation-fixture', 5)
    assert.deepEqual(web.getBytes(), Buffer.from([0xca, 0xfe, 0, 3]))
    web.cancel()
    console.log('session tickets: f10001/f10002, web callback ticket: cafe0003, all canceled')
}

run().then(() => process.exit(0), error => { console.error(error); process.exit(1) })
