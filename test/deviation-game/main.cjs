const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { app, BrowserWindow } = require('electron')

app.whenReady().then(async () => {
    assert.equal(app.isPackaged, true)
    assert.equal(require('steamworks.js/package.json').name, '@kyeshmz/steamworks.ts')
    assert.equal(require.resolve('steamworks.js'), join(app.getAppPath(), 'node_modules/steamworks.js/index.js'))
    const sdk = require('steamworks.js')
    assert.equal(sdk.isInitialized(), false)
    const libraries = readFileSync('/proc/self/maps', 'utf8')
    const dist = join(process.resourcesPath, 'app.asar.unpacked/node_modules/steamworks.js/dist/linux64')
    for (const binary of ['steamworksjs.linux-x64-gnu.node', 'libsteam_api.so']) {
        assert.ok(libraries.includes(join(dist, binary)), `Packaged process did not map ${binary} from ${dist}`)
    }
    const adapter = require('./adapter.cjs')
    if (process.env.FIXTURE_CASE === 'deviation-game') {
        const handlers = new Map()
        assert.equal(sdk.restartAppIfNecessary(3104020), false)
        const existing = new BrowserWindow({ show: false })
        const previousListeners = app.listenerCount('browser-window-created')
        await adapter.init({ handle(name, fn) { handlers.set(name, fn) } })
        const later = new BrowserWindow({ show: false })
        sdk.electronEnableSteamOverlay()
        assert.equal(app.listenerCount('browser-window-created'), previousListeners + 1)
        const call = (name, ...args) => handlers.get('STEAM_' + name)(undefined, ...args)
        assert.equal(sdk.isInitialized(), true)
        assert.equal(await call('GET_NAME'), 'Fixture Steam player')
        assert.equal(await call('GET_ID'), '76561198012345678')
        assert.equal(await call('APP_IS_INSTALLED'), true)
        assert.equal(await call('SET_STAT', 'GAMES_WON', 31), true)
        assert.equal(await call('STORE_STAT'), true)
        assert.equal(await call('GET_STAT', 'GAMES_WON'), 31)
        assert.equal(await call('TRIGGER_ACHIEVEMENT', 'FIXTURE_ACHIEVEMENT'), true)
        assert.equal(await call('CHECK_ACHIEVEMENT', 'FIXTURE_ACHIEVEMENT'), true)
        assert.equal(await call('CLEAR_ACHIEVEMENT', 'FIXTURE_ACHIEVEMENT'), true)
        assert.equal(await call('CHECK_ACHIEVEMENT', 'FIXTURE_ACHIEVEMENT'), false)
        assert.equal(await call('RESET_STAT'), true)
        assert.equal(await call('GET_STAT', 'GAMES_WON'), 0)
        assert.equal(await call('GET_SESSION_TICKET'), 'f10001')
        assert.deepEqual(await call('VERIFY_TICKET'), { error: 'STEAM_API_KEY not configured' })
        existing.destroy()
        later.destroy()
        console.log('Unmodified Deviation Game Steam IPC handlers passed with a fixture SDK')
    }
    console.log('Packaged Electron loaded the fork under steamworks.js')
    app.exit(0)
}).catch(error => {
    console.error(error)
    app.exit(1)
})
